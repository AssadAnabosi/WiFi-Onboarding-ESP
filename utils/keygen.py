"""Create OTA signing keys and maintain the firmware's trusted-key list.

Release keys (the default):
  python utils/keygen.py                     new key pair: private key in keys/ (never commit it),
                                             public key added to esp32/OtaPublicKey.h
  python utils/keygen.py --add-public K.pem  trust another public key (key rotation)
  python utils/keygen.py --remove ID         stop trusting a key (retire a leaked or old key)
  python utils/keygen.py --list              show the trusted release keys
  python utils/keygen.py --check K.pem       exit 0 if the key (private or public) is trusted

Dev key:
  python utils/keygen.py --dev               new dev key pair: private key in keys/ and
                                             esp32/OtaPublicKey.local.h (both gitignored).
                                             Builds that find that file are dev builds.
"""

import argparse
import hashlib
import sys
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sign import public_keys_from_header  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
KEYS_DIR = ROOT / "keys"
RELEASE_HEADER = ROOT / "esp32" / "OtaPublicKey.h"
DEV_HEADER = ROOT / "esp32" / "OtaPublicKey.local.h"

GENERATED_NOTICE = "// Generated by utils/keygen.py. Do not edit; rerun the script instead."


def der_of(public_key):
    return public_key.public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)


def key_id(public_key):
    return hashlib.sha256(der_of(public_key)).hexdigest()[:8]


def load_public_key(path):
    """Load a public key from a PEM file holding either a public or a private key."""
    data = Path(path).read_bytes()
    if b"PRIVATE KEY" in data:
        key = serialization.load_pem_private_key(data, password=None).public_key()
    else:
        key = serialization.load_pem_public_key(data)
    if not isinstance(key, ec.EllipticCurvePublicKey) or key.curve.name != "secp256r1":
        raise ValueError(f"{path}: expected an ECDSA P-256 key")
    return key


def render_header(prefix, keys, description):
    lines = ["#pragma once", GENERATED_NOTICE, f"// {description}", ""]
    entries = []
    for index, key in enumerate(keys):
        der = der_of(key)
        name = f"OTA_{prefix}_KEY_{index}_DER"
        lines.append(f"// key {key_id(key)}")
        lines.append(f"static const uint8_t {name}[] = {{")
        for i in range(0, len(der), 16):
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in der[i : i + 16]) + ",")
        lines.append("};")
        lines.append("")
        entries.append(f'{{"{key_id(key)}", {name}, sizeof({name})}},')
    lines.append(f"#define OTA_{prefix}_KEYS_LIST " + " ".join(entries))
    lines.append(f"#define OTA_{prefix}_KEY_COUNT {len(keys)}")
    lines.append("")
    return "\n".join(lines)


def write_release_header(keys, header=RELEASE_HEADER):
    text = render_header("RELEASE", keys, "Trusted release keys (ECDSA P-256, DER). Release builds trust only these.")
    header.write_bytes(text.encode("utf-8"))


def write_dev_header(key, header=DEV_HEADER):
    text = render_header("DEV", [key], "Dev key (gitignored). Its presence makes this a dev build.")
    header.write_bytes(text.encode("utf-8"))


def read_release_keys(header=RELEASE_HEADER):
    return public_keys_from_header(header) if header.exists() else []


def new_private_key(path, force=False):
    path = Path(path)
    if path.exists() and not force:
        raise ValueError(f"{path} already exists (use --force to replace it)")
    path.parent.mkdir(parents=True, exist_ok=True)
    key = ec.generate_private_key(ec.SECP256R1())
    pem = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption())
    path.write_bytes(pem)
    return key


def add_key(keys, key):
    if any(key_id(k) == key_id(key) for k in keys):
        return keys
    return keys + [key]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--dev", action="store_true", help="create the dev key pair")
    group.add_argument("--add-public", metavar="PEM", help="trust an existing public key")
    group.add_argument("--remove", metavar="ID", help="stop trusting the key with this ID")
    group.add_argument("--list", action="store_true", help="list trusted release keys")
    group.add_argument("--check", metavar="PEM", help="exit 0 if this key is trusted")
    parser.add_argument("--out", help="private key path (default: keys/ota-release.pem or keys/ota-dev.pem)")
    parser.add_argument("--force", action="store_true", help="replace an existing private key file")
    args = parser.parse_args(argv)

    try:
        keys = read_release_keys()
        if args.list:
            for key in keys:
                print(key_id(key))
            if not keys:
                print("no release keys trusted yet")
        elif args.check:
            wanted = key_id(load_public_key(args.check))
            trusted = any(key_id(k) == wanted for k in keys)
            print(f"key {wanted} is {'trusted' if trusted else 'NOT trusted'} by {RELEASE_HEADER.name}")
            return 0 if trusted else 1
        elif args.remove:
            remaining = [k for k in keys if key_id(k) != args.remove]
            if len(remaining) == len(keys):
                raise ValueError(f"no trusted key with ID {args.remove}")
            write_release_header(remaining)
            print(f"Removed key {args.remove}; {len(remaining)} release key(s) trusted")
        elif args.add_public:
            key = load_public_key(args.add_public)
            write_release_header(add_key(keys, key))
            print(f"Trusting key {key_id(key)}")
        elif args.dev:
            path = args.out or KEYS_DIR / "ota-dev.pem"
            key = new_private_key(path, args.force).public_key()
            write_dev_header(key)
            print(f"Dev key {key_id(key)}: private key {path}, public key {DEV_HEADER.relative_to(ROOT)}")
        else:
            path = args.out or KEYS_DIR / "ota-release.pem"
            key = new_private_key(path, args.force).public_key()
            write_release_header(add_key(keys, key))
            print(f"Release key {key_id(key)}: private key {path}, public key added to {RELEASE_HEADER.relative_to(ROOT)}")
            print("Store the private key as the OTA_SIGNING_KEY secret, back it up offline, and never commit it.")
        return 0
    except (ValueError, OSError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
