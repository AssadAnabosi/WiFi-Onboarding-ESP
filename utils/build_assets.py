"""Generate the firmware's embedded web UI and version headers.

Reads web-interface/ and VERSION, and writes:
  esp32/WebAssets.h  each file minified, gzipped and embedded as a byte array,
                     with its URL, MIME type, length and an ETag from its content hash.
                     Pages link their CSS/JS as "file?v=<hash>", so the browser can keep
                     those forever and only revalidate the page itself.
  esp32/Version.h    FIRMWARE_VERSION and its parts

Output is deterministic (zopfli gzip with timestamp 0 and no file name, pinned
minifiers), so CI can rerun this script and fail when the committed files drift.

Usage: python utils/build_assets.py
"""

import hashlib
import re
import sys
from pathlib import Path

import rjsmin
import zopfli.gzip
from css_html_js_minify import css_minify, html_minify

ROOT = Path(__file__).resolve().parent.parent
WEB_DIR = ROOT / "web-interface"
VERSION_FILE = ROOT / "VERSION"
OUT_DIR = ROOT / "esp32"

VERSION_PLACEHOLDER = "{{VERSION}}"
# Local stylesheet and script links in a page: href="css/x.css", src="js/x.js"
ASSET_LINK = re.compile(r'(href|src)="((?:css|js)/[^"?#]+)"')
VERSION_PATTERN = re.compile(r"^(\d+)\.(\d+)\.(\d+)$")

MIME_TYPES = {
    ".html": "text/html",
    ".css": "text/css",
    ".js": "application/javascript",
}

GENERATED_NOTICE = "// Generated by utils/build_assets.py. Do not edit; rerun the script instead."


def read_version(version_file):
    """Return the version string and its (major, minor, patch) parts."""
    version = version_file.read_text(encoding="utf-8").strip()
    match = VERSION_PATTERN.match(version)
    if not match:
        raise ValueError(f"{version_file}: expected MAJOR.MINOR.PATCH, got {version!r}")
    return version, tuple(int(part) for part in match.groups())


def url_for(relative_path):
    """Map a web-interface path to the URL the device serves it at."""
    if relative_path == "index.html":
        return "/"
    if relative_path.endswith(".html") and "/" not in relative_path:
        return "/" + relative_path[: -len(".html")]
    return "/" + relative_path


def add_asset_hashes(html, hashes, page):
    """Append ?v=<content hash> to every local CSS/JS link in a page."""

    def link(match):
        attr, target = match.groups()
        if target not in hashes:
            raise ValueError(f"{page}: links to {target}, which is not in web-interface/")
        return f'{attr}="{target}?v={hashes[target]}"'

    return ASSET_LINK.sub(link, html)


def minify(path, version, hashes=None):
    """Return the minified bytes of one web file (pages get their CSS/JS links hashed)."""
    suffix = path.suffix
    text = path.read_text(encoding="utf-8")
    if suffix == ".html":
        text = add_asset_hashes(text.replace(VERSION_PLACEHOLDER, version), hashes or {}, path.name)
        return html_minify(text).encode("utf-8")
    if suffix == ".css":
        return css_minify(text).encode("utf-8")
    if suffix == ".js":
        return rjsmin.jsmin(text).encode("utf-8")
    raise ValueError(f"Unsupported file type: {path}")


def content_hash(data):
    return hashlib.sha256(data).hexdigest()[:16]


def collect_assets(web_dir, version):
    """Return (url, mime, gzipped bytes, etag) for every web file, in a stable order.

    CSS/JS are built first so each page can link them by hash;
    a page's own ETag then changes whenever any file it links changes."""
    paths = sorted(
        (p for p in web_dir.rglob("*") if p.is_file() and p.suffix in MIME_TYPES),
        key=lambda p: p.relative_to(web_dir).as_posix(),
    )
    built = {}
    hashes = {}
    for path in paths:
        if path.suffix != ".html":
            relative = path.relative_to(web_dir).as_posix()
            built[path] = zopfli.gzip.compress(minify(path, version))
            hashes[relative] = content_hash(built[path])
    for path in paths:
        if path.suffix == ".html":
            built[path] = zopfli.gzip.compress(minify(path, version, hashes))
    assets = []
    for path in paths:
        relative = path.relative_to(web_dir).as_posix()
        data = built[path]
        assets.append((url_for(relative), MIME_TYPES[path.suffix], data, '"' + content_hash(data) + '"'))
    return assets


def c_bytes(data, indent="  ", per_line=16):
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i : i + per_line]
        lines.append(indent + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    return "\n".join(lines)


def render_web_assets(assets):
    out = [
        "#pragma once",
        GENERATED_NOTICE,
        "// Source: web-interface/",
        "",
        "#include <Arduino.h>",
        "",
        "/**",
        " * @brief One embedded, gzipped web file.",
        " */",
        "struct WebAsset",
        "{",
        "  const char *url;",
        "  const char *mime;",
        "  const uint8_t *data;",
        "  size_t length;",
        "  const char *etag;",
        "};",
        "",
    ]
    for index, (url, _mime, data, _etag) in enumerate(assets):
        out.append(f"// {url}")
        out.append(f"static const uint8_t WEB_ASSET_{index}[] PROGMEM = {{")
        out.append(c_bytes(data))
        out.append("};")
        out.append("")
    out.append("static const WebAsset WEB_ASSETS[] = {")
    for index, (url, mime, data, etag) in enumerate(assets):
        etag_literal = etag.replace('"', '\\"')
        out.append(f'  {{"{url}", "{mime}", WEB_ASSET_{index}, {len(data)}, "{etag_literal}"}},')
    out.append("};")
    out.append("")
    out.append("static const size_t WEB_ASSETS_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);")
    out.append("")
    return "\n".join(out)


def render_version(version, parts):
    major, minor, patch = parts
    return "\n".join(
        [
            "#pragma once",
            GENERATED_NOTICE,
            "// Source: VERSION",
            "",
            f'#define FIRMWARE_VERSION "{version}"',
            f"#define FIRMWARE_VERSION_MAJOR {major}",
            f"#define FIRMWARE_VERSION_MINOR {minor}",
            f"#define FIRMWARE_VERSION_PATCH {patch}",
            "",
        ]
    )


def write_if_changed(path, content):
    data = content.encode("utf-8")
    if path.exists() and path.read_bytes().replace(b"\r\n", b"\n") == data:
        return False
    path.write_bytes(data)
    return True


def build(web_dir=WEB_DIR, version_file=VERSION_FILE, out_dir=OUT_DIR):
    """Generate WebAssets.h and Version.h into out_dir. Returns the written paths."""
    version, parts = read_version(version_file)
    assets = collect_assets(web_dir, version)
    outputs = {
        out_dir / "WebAssets.h": render_web_assets(assets),
        out_dir / "Version.h": render_version(version, parts),
    }
    for path, content in outputs.items():
        changed = write_if_changed(path, content)
        print(f"{'updated' if changed else 'unchanged'}: {path.name}")
    total = sum(len(a[2]) for a in assets)
    print(f"{len(assets)} web files embedded, {total} bytes gzipped, version {version}")
    return list(outputs)


if __name__ == "__main__":
    try:
        build()
    except ValueError as error:
        sys.exit(f"error: {error}")
